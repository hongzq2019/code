CREATE TABLE IF NOT EXISTS sys_user (
  id BIGSERIAL PRIMARY KEY, username VARCHAR(40) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(16) NOT NULL, status VARCHAR(16) NOT NULL, must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  approved_by BIGINT, approved_at TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS dlt_draw (
  id BIGSERIAL PRIMARY KEY, issue_no VARCHAR(32) NOT NULL UNIQUE, draw_date DATE NOT NULL,
  front_numbers VARCHAR(32) NOT NULL, back_numbers VARCHAR(16) NOT NULL, source_url TEXT, source_payload TEXT,
  status VARCHAR(16) NOT NULL DEFAULT 'VALID', vector_status VARCHAR(16) NOT NULL DEFAULT 'PENDING', created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_dlt_draw_date ON dlt_draw(draw_date);
CREATE TABLE IF NOT EXISTS dlt_draw_number (
  id BIGSERIAL PRIMARY KEY, draw_id BIGINT NOT NULL REFERENCES dlt_draw(id) ON DELETE CASCADE, zone VARCHAR(8) NOT NULL,
  position SMALLINT NOT NULL, number SMALLINT NOT NULL, UNIQUE(draw_id,zone,position)
);
CREATE TABLE IF NOT EXISTS crawler_job_log (
  id BIGSERIAL PRIMARY KEY, job_type VARCHAR(64) NOT NULL, started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  finished_at TIMESTAMP WITH TIME ZONE, result VARCHAR(16) NOT NULL, fetched_count INTEGER NOT NULL DEFAULT 0,
  inserted_count INTEGER NOT NULL DEFAULT 0, error_message TEXT
);
CREATE TABLE IF NOT EXISTS prediction_record (
  id BIGSERIAL PRIMARY KEY, user_id BIGINT REFERENCES sys_user(id), input_type VARCHAR(32) NOT NULL,
  input_draw_id BIGINT REFERENCES dlt_draw(id), front_numbers VARCHAR(32) NOT NULL, back_numbers VARCHAR(16) NOT NULL,
  similar_draw_ids TEXT, model_version VARCHAR(32) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
